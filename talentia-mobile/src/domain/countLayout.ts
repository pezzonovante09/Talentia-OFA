/**
 * Силуэт кучки на экране по раскладке и числу — одна функция для гарда корпуса и рендерера
 * (аудит 2026-10-06, А12; `curriculum-content-reviewer` 2026-10-09). Два элемента с одним
 * силуэтом сравниваются узором, а не счётом: стимул «пять и остаток» и точки в рамке десятка
 * при одном числе выглядят одинаково, и навык счёта засчитывается за сравнение картинок.
 *
 * - ряд (`row`, по умолчанию): до пяти — линия, больше — две строки «пять и остаток»;
 * - точки как на кубике (`dice`): до пяти — кубик, больше — рамка десятка, тот же «пять и остаток»;
 * - вразброс (`scatter`): россыпи с одним числом считаются одинаковыми.
 *
 * Если рендерер нарисует раскладку иначе — менять здесь, иначе гард и экран разойдутся.
 */
export type CountLayout = 'row' | 'scatter' | 'dice';

export function countSilhouette(layout: CountLayout | undefined, count: number): string {
  const l = layout ?? 'row';
  if (l === 'scatter') return `scatter:${count}`;
  if (count > 5) return `five-and:${count - 5}`;
  return l === 'dice' ? `dice:${count}` : `line:${count}`;
}
