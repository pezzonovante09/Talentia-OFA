/**
 * Схема заданий. Спецификация — `FORMATS.md` в корне репозитория.
 *
 * Главное отличие от прежней схемы: формат описывает **действие**, а не подачу.
 * Раньше `multiple_choice` и `world_knowledge` были разными типами, хотя ребёнок
 * в обоих тыкает в один вариант из нескольких — отличались они лишь тем, что в
 * одном варианты текстом, а в другом картинкой. Из-за этого, чтобы добавить
 * картиночный вопрос, автору приходилось заводить новый формат вместо флага, и
 * из двенадцати типов наполнили два.
 */

export type AgeBand = '5-6' | '7' | '8' | '9-10';

/**
 * Как показаны элементы задания.
 *
 * До 7 лет допустима только `picture`, и каждый элемент обязан быть озвучен:
 * нечитающий ребёнок не «хуже справится» с текстовым интерфейсом — для него
 * такого интерфейса не существует. Ограничение лежит на подаче, а не на
 * действии: сами действия малышу доступны почти все.
 */
export type Presentation = 'picture' | 'text';

/** Элемент, который ребёнок видит: подпись, картинка, озвучка. */
export type Media = {
  /**
   * Ключ локали. Он же адресует озвучку: файл лежит по пути
   * `voice/<язык>/<этот ключ>.m4a`. Отдельного поля под звук нет намеренно —
   * когда их два, текст и голос рано или поздно расходятся, и ребёнок слышит
   * одно, а видит другое. Один ключ такую ошибку делает невозможной.
   * `voice: 'select'` — до ответа нейтральный звук выбора, имя `labelKey` звучит после
   * верного ответа или показа (№88).
   */
  labelKey: string;
  /**
   * «Немая» карточка проверяемого символа (решение №88): в навыке с `SkillEntry.symbol`
   * цифра, буква или слог до ответа не называется — иначе ответ находится на слух. Без
   * поля элемент звучит именем. Только у элемента без `shape` и `image`; гард `symbolVoice`.
   */
  voice?: 'select';
  /**
   * Язык, на котором элемент показывается всегда, независимо от языка
   * интерфейса. Нужен там, где содержание и есть язык: английское слово в
   * Мастерской, русский слог в Побережье слов. Такие элементы не переводятся.
   */
  lang?: 'ru' | 'en' | 'ky';
  /**
   * Имя фигуры, которую рисует вектором `<CountableShape>`, либо имя файла в
   * `assets/images/items`. Для заданий на счёт хватает фигур: рисовать камень
   * кружком дешевле, чем заводить картинку, и стиль совпадает гарантированно.
   */
  shape?: 'stone' | 'berry' | 'leaf' | 'dot';
  image?: string;
  /**
   * Сколько фигур нарисовать. Только вместе с `shape`; целое ≥ 1. **Ноль — только в корзинке**
   * (`container`): пустая карточка без контейнера в задании на счёт — ошибка (гард `shapeCount`).
   */
  count?: number;
  /**
   * Кучка лежит в корзинке (решение №136; SCREENS.md 3.8 «Ноль — пустая корзинка»): ноль — та же
   * корзинка без фигур, и в задании, где есть корзинка, **все** кучки лежат в одинаковых корзинках —
   * иначе ноль узнаётся по отсутствию корзинки, а не по пустоте (гард `basketAll`). Рисуется вектором
   * вместе с `<CountableShape>`, картинки не требует. Только вместе с `shape`.
   */
  container?: 'basket';
  /**
   * Как разложены фигуры. Раскладка — рычаг трудности задания на счёт: ряд считается
   * легче россыпи, а точки «как на кубике» узнаются сразу, без пересчёта. Без поля — ряд.
   * Только вместе с `shape`.
   */
  layout?: 'row' | 'scatter' | 'dice';
  /**
   * Карточка-число: крупная цифра на табличке (SCREENS.md 3.8), озвучка — `labelKey`
   * (название числа). На 5–6 цифра — подпись, опора — звучащее число («кучка → число»,
   * решение №81). Без `shape`, `count` и `layout`; 0–10. В навыке с `symbol` — немая:
   * `voice: 'select'` (№88).
   */
  numeral?: number;
};

/**
 * Вставка материала на другом языке в вопрос — «Найди букву {{t}}» при ky-интерфейсе
 * (FORMATS.md, «Язык»; аудит 2026-10-06, А23). Вставка не склоняется; падеж несёт слово-
 * классификатор вопроса. Звучит голосом своего языка.
 */
export type PromptInsert = {
  /** Текст вставки — ключ локали материала. */
  textKey: string;
  lang: 'ru' | 'en' | 'ky';
  audioKey?: string;
};

type BaseTask = {
  id: string;
  /** Ключ вопроса. На полосе 5-6 он звучит голосом, а не читается. */
  promptKey: string;
  /** Вставки в вопрос по плейсхолдерам `{{t}}` — гард `promptInserts`. */
  inserts?: Record<string, PromptInsert>;
  /**
   * Навык, который задание проверяет, — например `count-to-5`. По нему
   * работает интервальное повторение: повторяется навык, а не урок. Один
   * навык живёт в нескольких уроках и нескольких формулировках.
   */
  skill: string;
  /**
   * Подсказка после первой ошибки. Ровно одна: вторую ступень приложение
   * строит само, показывая верный ответ, — см. «Ошибка» в FORMATS.md.
   */
  hintKey: string;
  /**
   * То, о чём спрашивают: группа предметов, картинка, слово. В задании
   * «сколько их?» без этого поля нечего считать.
   */
  stimulus?: Media;
  /**
   * Объяснение при показе ответа (вторая ступень после ошибки): называет ответ и
   * говорит, почему он такой, — «Смотри: раз, два, три — их три.». Подсказка
   * (`hintKey`) ведёт к способу и ответа не называет. Одна реплика на 5-6, одна-две с
   * 7 лет — вторая сменяет первую в пузыре, и первая сама называет ответ. Обязательно у
   * оценочного задания, у знакомства — по желанию. FORMATS.md, «Объяснение при показе
   * ответа»; лимиты — `EXPLAIN_LINES`, `EXPLAIN_CHARS`.
   */
  explainKey?: string[];
  /**
   * Отрывок с условием текстовой задачи. Только условие: вопрос остаётся в
   * `promptKey`. Лежит на задании, а не на уроке, — задание уходит повторением в
   * чужой урок; общий текст — один `textKey` у нескольких заданий. На 5-6 только
   * звучит, а на картинке есть каждый названный в нём предмет. Только `choose`,
   * `order`, `build`; лимиты — `PASSAGE_LIMITS`.
   */
  passage?: { textKey: string; image?: string };
  /**
   * Знакомство с форматом: первое задание урока, где ребёнок впервые видит, как
   * формат работает. Допускает две альтернативы и **в зачёт не идёт** — ни в
   * коробки навыка, ни в звёзды: из двух вариантов угадывают в половине случаев.
   * Не больше одного на урок и только первым; в уроке с разобранным примером
   * (`Lesson.model`) его нет — «теперь ты» уже знакомит с форматом (решение №28).
   * Лимиты — `domain/lessonLimits.ts`.
   */
  intro?: true;
};

/** Выбрать один вариант: 3 на полосе 5–6, 3–4 с 7 лет (`lessonLimits`). Узнавание. */
export type ChooseTask = BaseTask & {
  format: 'choose';
  presentation: Presentation;
  options: (Media & { id: string; correct: boolean })[];
};

/**
 * Показать место на картинке. Пространственное мышление. С 4 лет.
 *
 * Зоны заданы долями кадра, а не пикселями: сцена растягивается под ширину
 * экрана, и пиксельные координаты разъехались бы на первом же другом телефоне.
 */
export type PointTask = BaseTask & {
  format: 'point';
  scene: string;
  targets: {
    id: string;
    x: number;
    y: number;
    /** Радиус в долях ширины кадра. Не меньше 0.1 — палец ребёнка крупный. */
    r: number;
    correct: boolean;
    /**
     * Название зоны. Обязательно: тап по зоне её озвучивает, и скринридер читает
     * каждую зону отдельным элементом (SCREENS.md, 3.2 и 6) — зона без названия для
     * нечитающего ребёнка и для незрячего не существует. Ключ привязан к сцене, а не
     * к заданию: одна сцена обслуживает несколько заданий.
     */
    labelKey: string;
  }[];
};

/** Соединить пары. Связь между понятиями. С 5 лет. Тап по одному, тап по второму. */
export type MatchTask = BaseTask & {
  format: 'match';
  presentation: Presentation;
  pairs: { id: string; left: Media; right: Media }[];
};

/** Разложить по порядку. Последовательность. С 5 лет. */
export type OrderTask = BaseTask & {
  format: 'order';
  presentation: Presentation;
  /** `position` — верный порядок, от нуля. Порядок показа перемешивается. */
  items: (Media & { id: string; position: number })[];
};

/**
 * Разложить по группам. Классификация. С 5 лет: раскладка по одному признаку
 * посильна пятилетке, а на полосе 5–6 — две группы и 3–4 предмета.
 */
export type GroupTask = BaseTask & {
  format: 'group';
  presentation: Presentation;
  groups: { id: string; labelKey: string; shape?: Media['shape']; image?: string }[];
  items: (Media & { id: string; groupId: string })[];
};

/** Собрать ответ из фрагментов или ввести. Припоминание, а не узнавание. С 7 лет. */
export type BuildTask = BaseTask & {
  format: 'build';
  /** Готовые фрагменты для сборки; без них — ввод с клавиатуры. */
  fragments?: { id: string; labelKey: string }[];
  answer: string;
};

export type Task = ChooseTask | PointTask | MatchTask | OrderTask | GroupTask | BuildTask;
export type TaskFormat = Task['format'];

/** С какого возраста доступен формат. */
export const FORMAT_MIN_BAND: Record<TaskFormat, AgeBand> = {
  choose: '5-6',
  point: '5-6',
  match: '5-6',
  order: '5-6',
  group: '5-6',
  build: '7',
};

type DistributiveOmit<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never;

/**
 * Задача разобранного примера: задание без того, что нужно только оценке, — id, навык
 * (он на `LessonModel`), подсказка, объяснение, знакомство. Отрывка нет: план задачи
 * показывается на условии в одну фразу.
 */
export type ModelExample = DistributiveOmit<Task, 'id' | 'skill' | 'hintKey' | 'explainKey' | 'intro' | 'passage'>;

/**
 * Шаг примера: реплика Tali и одно действие — элемент `example` (его id), который он
 * ставит или подсвечивает, или `'stimulus'` — сам стимул («гляжу на все листья разом»).
 */
export type ModelStep = {
  lineKey: string;
  reveal?: string;
  /**
   * Tali ошибается (роль третьего урока темы, TALI.md; разбор 2026-10-31, вопрос 70): `reveal` —
   * **неверный** элемент, реплика с вопросом («Это пять?»), поза `puzzled`, над плиткой знак вопроса,
   * не крест. Следующий шаг раскрывает верный; ребёнок поправляет в «теперь ты». Не больше одного на
   * пример, только в третьем уроке темы (гард `model`).
   */
  mistake?: true;
};

/** Значение `ModelStep.reveal` для стимула: у стимула нет id. */
export const REVEAL_STIMULUS = 'stimulus';

/**
 * Разобранный пример: новое правило ребёнок сначала видит решённым, а не как тест.
 * Только в уроке, где навык впервые встречается в своей полосе. Tali решает `example`
 * вслух на экране того же формата, что первое задание навыка; последний шаг — «теперь
 * ты» (ведомый тап) — строит приложение, в `steps` его нет. Не идёт ни в зачёт, ни в
 * звёзды, ни в лимит заданий. FORMATS.md, «Разобранный пример»; лимиты — `MODEL_STEPS`,
 * `MODEL_SECONDS`.
 */
export type LessonModel = { skill: string; example: ModelExample; steps: ModelStep[] };

export type Lesson = {
  id: string;
  titleKey: string;
  band: AgeBand;
  /**
   * Завязка: поза Tali и его реплика. На 5-6 в уроке с примером — одна реплика ≤ 36
   * знаков: иначе до первого настоящего ответа пятилетка слишком долго только слушает.
   */
  hook: { taliPose: 'hello' | 'found' | 'point' | 'cheer' | 'puzzled' | 'write'; lineKey: string };
  /** Разобранный пример — в уроке с новым навыком, и только в нём. */
  model?: LessonModel;
  tasks: Task[];
  /** Что вписывается в атлас по итогам урока. */
  atlasEntryKey: string;
};

export type Topic = {
  id: string;
  titleKey: string;
  /**
   * Языки интерфейса, при которых тема вообще существует. Пусто — при любом. У тем Побережья
   * слов и кыргызского региона поля нет: они видны при любом интерфейсе — Tali говорит на языке
   * интерфейса, а материал помечен `lang` (решения №47, №48; `domain/regionVisibility.ts`).
   */
  instructionLanguages?: ('ru' | 'en' | 'ky')[];
  /**
   * Класс школы — только у тем полосы 9-10: она объединяет 3 и 4 класс, а ребёнок может
   * начать с 4-го (решение №40). Темы 4 класса идут в корпусе после тем 3-го; на 7 и 8
   * класс один (1 и 2) и не пишется.
   */
  grade?: 3 | 4;
  lessons: Lesson[];
};
export type Region = {
  /**
   * `kyrgyz` — родной кыргызский (решение №5): на карте только при включённом
   * кыргызском у ребёнка (№38). Цвет и панорама — шаг 6 (`design-lead`, ассеты).
   */
  id: 'numbers' | 'words' | 'nature' | 'workshop' | 'kyrgyz';
  titleKey: string;
  topics: Topic[];
};
